#!/usr/bin/env python3
"""Builds the generated parts of the project page (``website/index.html``) from the paper's assets.

Nothing on the page that comes from a result is typed by hand:

* Tables I-III   <- ``paper/tables/{table_bench,table1,table3}.tex`` (written by ``analysis/paper_assets.py``)
* benchmark chart <- ``analysis/out/bench_summary.csv``
* figures         <- ``paper/figs/results.pdf`` (Fig. 2) and the TikZ source of Fig. 1 in ``paper/main.tex``

Each generated block sits between ``<!-- BEGIN generated:NAME -->`` and ``<!-- END generated:NAME -->``.

    python website/build.py             # rewrite the generated blocks of index.html
    python website/build.py --figures   # also re-render static/method.svg, static/results.svg, static/social.png
    python website/build.py --check     # exit 1 if a generated block is out of date (used by tests/)
"""
from __future__ import annotations

import argparse
import csv
import html
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "website"
INDEX = SITE / "index.html"
TABLES = ROOT / "paper" / "tables"
BENCH_CSV = ROOT / "analysis" / "out" / "bench_summary.csv"

#: Display names of the benchmark targets (``target`` column of bench_summary.csv), as in Table I.
BENCH_NAMES = {"sslmos": "SSL-MOS", "utmos": "UTMOS22", "nisqa": "NISQA", "dnsmos": "DNSMOS OVRL"}

MINUS = "\u2212"


# ------------------------------------------------------------------ LaTeX -> HTML
def tex_cell(s: str) -> str:
    """Converts one cell of a generated LaTeX table to HTML."""
    s = s.strip()
    s = re.sub(r"\$R_(\d)\^\{\\mathrm\{multi\}\}\$", r"R<sub>\1</sub><sup>multi</sup>", s)
    s = re.sub(r"\$R_(\d)\$", r"R<sub>\1</sub>", s)
    s = s.replace(r"$R(\hat{x})\!-\!R(x)$", f"R(<i>x&#770;</i>) {MINUS} R(<i>x</i>)")
    s = s.replace(r"$\Delta$", "&Delta;")
    s = re.sub(r"(?<![\w.])-(?=\d)", MINUS, s)
    if "$\\pm$" in s:
        mean, sd = s.split("$\\pm$")
        return f'{mean}<span class="sd">&plusmn;{sd}</span>'
    assert "$" not in s and "\\" not in s, f"unconverted LaTeX in table cell: {s!r}"
    return s


def tex_header_cells(row: str) -> list[str]:
    """Header cells of a LaTeX row as ``<th>`` elements (``\\multicolumn`` becomes ``colspan``)."""
    out = []
    for c in row.split("&"):
        c = c.strip()
        m = re.fullmatch(r"\\multicolumn\{(\d+)\}\{\w\}\{(.*)\}", c)
        if m:
            out.append(f'<th colspan="{m.group(1)}" class="group">{tex_cell(m.group(2))}</th>')
        else:
            out.append(f'<th scope="col">{tex_cell(c)}</th>' if c else "<td></td>")
    return out


def table_html(tex_path: Path, caption_id: str) -> str:
    """Renders a ``booktabs`` table generated by ``analysis/paper_assets.py`` as an HTML table."""
    rows = [ln.strip() for ln in tex_path.read_text().splitlines()]
    rows = [r for r in rows if r and not r.startswith(("%", "\\begin", "\\end", "\\toprule", "\\bottomrule",
                                                         "\\cmidrule"))]
    mid = rows.index("\\midrule")
    strip = lambda r: re.sub(r"\\\\$", "", r).strip()  # noqa: E731
    head = [strip(r) for r in rows[:mid]]
    body = [strip(r) for r in rows[mid + 1:]]
    lines = [f'<table aria-describedby="{caption_id}">', "<thead>"]
    for r in head:
        lines.append("<tr>" + "".join(tex_header_cells(r)) + "</tr>")
    lines += ["</thead>", "<tbody>"]
    for r in body:
        first, *rest = (tex_cell(c) for c in r.split("&"))
        lines.append(f'<tr><th scope="row">{first}</th>' + "".join(f"<td>{c}</td>" for c in rest) + "</tr>")
    lines += ["</tbody>", "</table>"]
    return "\n".join(lines)


# ------------------------------------------------------------- benchmark chart
def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def signed(x: float, nd: int) -> str:
    return (f"+{x:.{nd}f}" if x >= 0 else f"{MINUS}{-x:.{nd}f}")


def bench_chart_html() -> str:
    """One row per predictor: mean ASR (bar), range over the five attackers, naive-reference mean."""
    with open(BENCH_CSV) as f:
        rows = sorted(csv.DictReader(f), key=lambda r: -float(r["asr_ref_recon_mean"]))
    out = []
    for r in rows:
        name = BENCH_NAMES[r["target"]]
        mean, lo, hi = (float(r[f"asr_ref_recon_{k}"]) for k in ("mean", "min", "max"))
        naive = float(r["asr_ref_input_mean"])
        gain, offset = float(r["gain_ref_recon_mean"]), float(r["recon_gain_mean"])
        tip = (f"{name}: hacked on {pct(mean)} of utterances (mean of {r['n_attackers']} attackers), "
               f"{pct(lo)} to {pct(hi)} across attackers; {pct(naive)} under the naive reference. "
               f"Mean gain {signed(gain, 3)} MOS; codec round-trip offset {signed(offset, 2)} MOS.")
        out.append(
            f'<div class="bench-row" role="listitem" tabindex="0" '
            f'style="--mean:{mean:.4f};--lo:{lo:.4f};--hi:{hi:.4f};--naive-asr:{naive:.4f}">\n'
            f'  <span class="bench-name">{name}</span>\n'
            f'  <span class="bench-track" aria-hidden="true"><span class="bench-bar"></span>'
            f'<span class="bench-range"></span><span class="bench-naive"></span></span>\n'
            f'  <span class="bench-value">{pct(mean)}</span>\n'
            f'  <span class="bench-tip">{html.escape(tip)}</span>\n'
            f"</div>")
    return "\n".join(out)


# --------------------------------------------------------------------- figures
def render_figures() -> None:
    """Re-renders Fig. 1 (from its TikZ source), Fig. 2 and the social preview image."""
    static = SITE / "static"
    static.mkdir(exist_ok=True)
    tex = (ROOT / "paper" / "main.tex").read_text()
    tikz = re.search(r"\\begin\{tikzpicture\}\[.*?\\end\{tikzpicture\}", tex, re.S).group(0)
    doc = ("\\documentclass{article}\n\\usepackage{mathptmx}\n\\usepackage{tikz}\n"
           "\\usetikzlibrary{arrows.meta,positioning,calc,fit,backgrounds}\n\\newsavebox\\fig\n"
           "\\begin{document}\n\\sbox\\fig{%\n" + tikz + "}\n"
           "\\hoffset=-1in \\voffset=-1in\n"
           "\\pdfpagewidth=\\dimexpr\\wd\\fig+6pt\\relax\n"
           "\\pdfpageheight=\\dimexpr\\ht\\fig+\\dp\\fig+6pt\\relax\n"
           "\\shipout\\vbox{\\kern3pt\\hbox{\\kern3pt\\box\\fig}}\n\\end{document}\n")
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "method.tex").write_text(doc)
        subprocess.run(["pdflatex", "-interaction=nonstopmode", "method.tex"], cwd=tmp, check=True,
                       capture_output=True)
        subprocess.run(["pdftocairo", "-svg", f"{tmp}/method.pdf", str(static / "method.svg")], check=True)
    results = ROOT / "paper" / "figs" / "results.pdf"
    subprocess.run(["pdftocairo", "-svg", str(results), str(static / "results.svg")], check=True)
    subprocess.run(["pdftocairo", "-png", "-singlefile", "-scale-to-x", "1200", "-scale-to-y", "-1",
                    str(results), str(static / "social")], check=True)


# ------------------------------------------------------------------------ main
def blocks() -> dict[str, str]:
    return {"bench-chart": bench_chart_html(),
            "table-bench": table_html(TABLES / "table_bench.tex", "cap-table1"),
            "table-loop": table_html(TABLES / "table1.tex", "cap-table2"),
            "table-downstream": table_html(TABLES / "table3.tex", "cap-table3")}


def fill(page: str, generated: dict[str, str]) -> str:
    for name, content in generated.items():
        pat = re.compile(rf"^( *)(<!-- BEGIN generated:{name} -->).*?(<!-- END generated:{name} -->)", re.S | re.M)
        if not pat.search(page):
            raise KeyError(f"index.html has no generated block {name!r}")
        page = pat.sub(lambda m: f"{m.group(1)}{m.group(2)}\n{content}\n{m.group(1)}{m.group(3)}", page)
    return page


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only check that index.html is up to date")
    ap.add_argument("--figures", action="store_true", help="also re-render the figures (pdflatex, pdftocairo)")
    args = ap.parse_args()
    page = INDEX.read_text()
    new = fill(page, blocks())
    if args.check:
        if new != page:
            sys.exit("website/index.html is out of date: run python website/build.py")
        print("website/index.html is up to date")
        return
    INDEX.write_text(new)
    if args.figures:
        render_figures()
    print(f"wrote {INDEX.relative_to(ROOT)}" + (" and website/static/" if args.figures else ""))


if __name__ == "__main__":
    main()
